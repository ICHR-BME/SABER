"""Scripted reach demonstrations for T1-R on the real arm (no gripper, no teleoperation device).

Decision 2026-11-19 (Ian): demos are generated by a scripted controller instead of GELLO /
SpaceMouse. Each demo starts at the measured home pose and moves the wrist camera, looking straight
down, over the goal zone at the T1-R final height. Images and joint states are real; only the
motion is scripted. To avoid every demo following the same path, each one gets a random via point
above the goal and a small random final offset (seeded, recorded in the episode metadata).

Paths (``path``):
  "descend"   (2026-11-19) straight line from home to a via point 8 cm above the goal, then down.
              Home is above the middle of the grid, so the first ~3 s are mostly a descent and the
              demos for different goals differ by only ~4 cm there.
  "xy_first"  (2026-11-21) first a horizontal move at the starting height until the camera is
              above the goal (via point, jittered), then straight down. The goal-specific part of
              the motion comes first, where the instruction has to decide it (first live SmolVLA
              runs ignored the instruction; see docs/DECISIONS.md).

Paper caveat: scripted demos are less varied than human teleoperation; report it.
"""

from __future__ import annotations

from typing import Any

import numpy as np

from saber.robots.xarm6.driver import array_to_action
from saber.robots.xarm6.kinematics import forward_kinematics, inverse_kinematics
from saber.teleop.base import current_joints

DOWN = forward_kinematics(np.zeros(6))[:3, :3]  # tool z axis points down at q = 0


class ScriptedReach:
    def __init__(
        self,
        goal_xy: np.ndarray,
        final_z: float,
        tcp_offset: np.ndarray,
        speed_m_s: float,
        dt: float,
        rng: np.random.Generator,
        via_height_m: float = 0.08,
        via_jitter_m: float = 0.03,
        final_jitter_m: float = 0.005,
        hold_s: float = 1.0,
        joint_lower: np.ndarray | None = None,
        joint_upper: np.ndarray | None = None,
        margin_deg: float = 1.0,
        path: str = "descend",
    ):
        if path not in ("descend", "xy_first"):
            raise ValueError(f"unknown path {path!r}")
        self.path = path
        self.tcp_offset = np.asarray(tcp_offset, dtype=float)
        self.goal_xy = np.asarray(goal_xy, dtype=float)[:2]
        self.final_z = float(final_z)
        self.rng = rng
        self.via_height_m = via_height_m
        self.via_jitter_m = via_jitter_m
        # Truncated jitter (at most 1.5 sigma): a 2.4-sigma draw put the via point 7 cm towards the base
        # and drove J3 past the controller limit on the real arm (2026-11-19, demo 36, code -8).
        self.final = np.array([*(self.goal_xy + self._jitter(final_jitter_m)), self.final_z])
        self.via = self._draw_via()
        self.step_len = speed_m_s * dt
        self.hold_steps = max(1, int(round(hold_s / dt)))
        m = np.deg2rad(margin_deg)
        self.lower = None if joint_lower is None else np.asarray(joint_lower, dtype=float) + m
        self.upper = None if joint_upper is None else np.asarray(joint_upper, dtype=float) - m
        self.via_redraws = 0
        self._plan: list[np.ndarray] | None = None
        self._q_plan: list[np.ndarray] | None = None
        self._i = 0

    def _jitter(self, sigma: float) -> np.ndarray:
        return np.clip(self.rng.normal(0.0, sigma, 2), -1.5 * sigma, 1.5 * sigma)

    def _draw_via(self) -> np.ndarray:
        # xy_first: the height is the start height, filled in by _build once the start pose is known
        z = np.nan if self.path == "xy_first" else self.final_z + self.via_height_m
        return np.array([*(self.goal_xy + self._jitter(self.via_jitter_m)), z])

    def connect(self) -> None:
        pass

    def disconnect(self) -> None:
        pass

    def describe(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "via_m": [float(v) for v in self.via],
            "final_m": [float(v) for v in self.final],
            "via_redraws": self.via_redraws,
        }

    def _cartesian_plan(self, start: np.ndarray) -> list[np.ndarray]:
        plan: list[np.ndarray] = []
        prev = start
        for p in (self.via, self.final):
            n = max(1, int(np.ceil(np.linalg.norm(p - prev) / self.step_len)))
            plan.extend(prev + (p - prev) * k / n for k in range(1, n + 1))
            prev = p
        plan.extend([self.final] * self.hold_steps)
        return plan

    def _joint_plan(self, q0: np.ndarray, plan: list[np.ndarray]) -> list[np.ndarray] | None:
        """IK along the whole path; None if any configuration leaves the joint limits (with margin)."""
        out: list[np.ndarray] = []
        q = q0
        for p in plan:
            goal = np.eye(4)
            goal[:3, :3] = DOWN
            goal[:3, 3] = p
            q, _ = inverse_kinematics(goal, q, self.tcp_offset, max_iters=60)
            if self.lower is not None and (np.any(q < self.lower) or np.any(q > self.upper)):
                return None
            out.append(q)
        return out

    def _build(self, q0: np.ndarray) -> None:
        start = forward_kinematics(q0, self.tcp_offset)[:3, 3]
        for attempt in range(21):
            if attempt == 20:  # fall back to a via point straight above the final point
                z = start[2] if self.path == "xy_first" else self.final_z + 0.03
                self.via = np.array([*self.final[:2], z])
            if self.path == "xy_first":
                self.via[2] = start[2]
            plan = self._cartesian_plan(start)
            q_plan = self._joint_plan(q0, plan)
            if q_plan is not None:
                self._plan, self._q_plan = plan, q_plan
                return
            self.via_redraws += 1
            if attempt < 19:
                self.via = self._draw_via()
        raise RuntimeError(f"no feasible scripted path to {self.final.round(3).tolist()} within joint limits")

    def get_action(self, observation: dict[str, Any]) -> dict[str, float] | None:
        if self._q_plan is None:
            self._build(current_joints(observation))
        assert self._q_plan is not None
        if self._i >= len(self._q_plan):
            return None
        q_new = self._q_plan[self._i]
        self._i += 1
        return array_to_action(q_new, 0.0)


def go_home(robot: Any, home_rad: np.ndarray, realtime: bool = True, tol_deg: float = 0.3) -> int:
    """Move to the home joints through the normal (clipped) action path. Not recorded."""
    import time

    period = 1.0 / robot.config.control_hz
    for n in range(int(60 * robot.config.control_hz)):  # at most 60 s
        q = robot.joint_positions()
        if np.max(np.abs(np.rad2deg(home_rad - q))) < tol_deg:
            return n
        t0 = time.monotonic()
        robot.send_action(array_to_action(home_rad, 0.0))
        if realtime:
            time.sleep(max(0.0, period - (time.monotonic() - t0)))
    raise RuntimeError("could not reach home within 60 s")
